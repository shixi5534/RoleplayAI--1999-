def main() -> int:
    CACHE.mkdir(parents=True, exist_ok=True)
    written = 0
    for h, ents, rels in E:
        payload = {"entities": ents, "relations": rels}
        (CACHE / f"{h}.json").write_text(
            json.dumps(payload, ensure_ascii=False), encoding="utf-8"
        )
        written += 1
    print(f"[backfill] 写入缓存 {written} 块 → {CACHE}")
    # 自检：所有 relation 谓语必须是 canonical 或可映射同义词
    sys.path.insert(0, str(ROOT / "src"))
    from roleplay.core.knowledge.relation_vocab import canonicalize_relation

    bad = []
    for _h, _e, rels in E:
        for r in rels:
            if canonicalize_relation(r["relation"]) is None:
                bad.append(r["relation"])
    print("[backfill] 词表外谓语:", sorted(set(bad)) or "无")
    return 0


