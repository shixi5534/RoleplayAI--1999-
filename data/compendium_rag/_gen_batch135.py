def main() -> int:
    dump_keys = {}
    for line in DUMP.read_text(encoding="utf-8-sig").splitlines():
        line = line.strip()
        if line:
            o = json.loads(line)
            dump_keys[o["key"]] = o["chunk_id"]

    missing = [k for k in dump_keys if k not in BATCH]
    extra = [k for k in BATCH if k not in dump_keys]
    assert not missing, f"dump 中未覆盖: {missing}"
    assert not extra, f"多余 key: {extra}"

    out = ROOT / "_agent_batch135.json"
    out.write_text(json.dumps(BATCH, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"写出 {len(BATCH)} 块 → {out}")

    bad = 0
    for k in dump_keys:
        v = BATCH[k]
        names = {e["name"] for e in v["entities"]}
        miss = {r[s] for r in v["relations"] for s in ("src", "dst") if r[s] not in names}
        if miss:
            bad += 1
            print(f"  [!] {dump_keys[k]} 缺失端点: {sorted(miss)}")
    print(f"端点检查：{len(dump_keys) - bad}/{len(dump_keys)} 块通过")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
