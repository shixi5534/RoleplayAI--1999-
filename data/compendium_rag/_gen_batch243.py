def audit(name, B, dump):
    keys = [json.loads(l)["key"]
            for l in (ROOT / dump).read_text(encoding="utf-8-sig").splitlines() if l.strip()]
    assert len(keys) == len(B) and set(keys) == set(B), f"{name}: 块数/key 不匹配"
    bad = []
    for k, blk in B.items():
        names = {e["name"] for e in blk["entities"]}
        assert len(names) == len(blk["entities"]), f"{k}: 重名"
        for i, r in enumerate(blk["relations"]):
            for s in ("src", "dst"):
                if r[s] not in names:
                    bad.append(f"{k}[r{i}]{s}={r[s]}")
            if not 2 <= len(r["relation"]) <= 6:
                bad.append(f"{k}[r{i}]len={r['relation']}")
            if r["src"] == r["dst"]:
                bad.append(f"{k}[r{i}]自环:{r['src']}")
        for e in blk["entities"]:
            if len(e["desc"]) > 30:
                bad.append(f"{k}:desc超长={e['name']}")
    if bad:
        raise SystemExit(f"batch{name} 端点体检失败:\n  - " + "\n  - ".join(bad))
    print(f"batch{name}: {len(B)} 块 ✅")


