    assert len(keys) == len(BATCH), f"dump 块数 {len(keys)} != 生成块数 {len(BATCH)}"
    miss = [k for k in keys if k not in BATCH]
    extra = [k for k in BATCH if k not in keys]
    assert not miss and not extra, f"key 不匹配 miss={miss} extra={extra}"
