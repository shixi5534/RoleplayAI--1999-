bad = []
for k, blk in B.items():
    text = re.sub(f"[{QUOTE}]", "", dump[k])
    names = {e["name"] for e in blk["entities"]}
    assert len(names) == len(blk["entities"]), f"{k}: 块内重名"
    for i, r in enumerate(blk["relations"]):
        for s in ("src", "dst"):
            if r[s] not in names:
                bad.append(f"{k}[r{i}] 端点不在块内: {r[s]}")
        if not 2 <= len(r["relation"]) <= 6 or not re.fullmatch(r"[一-鿿]{2,6}", r["relation"]):
            bad.append(f"{k}[r{i}] 关系非法: {r['relation']}")
        if r["src"] == r["dst"]:
            bad.append(f"{k}[r{i}] 自环: {r['src']}")
        ev = re.sub(f"[{QUOTE}]", "", r["evidence"])
        if len(ev) > 40:
            bad.append(f"{k}[r{i}] evidence 超长({len(ev)}): {ev}")
        if ev not in text:
            bad.append(f"{k}[r{i}] evidence 非原文子串: {ev}")
    for e in blk["entities"]:
        if not 1 <= len(e["desc"]) <= 30:
            bad.append(f"{k}: desc 长度={len(e['desc'])} {e['name']}")
        if e["name"] in e["aliases"]:
            bad.append(f"{k}: 别名与本体同名 {e['name']}")
        for a in e["aliases"]:
            if a not in text:
                bad.append(f"{k}: 别名 {a} 未在本块出现(不该声明)")
if bad:
    print("\n".join(bad))
    raise SystemExit(f"❌ 体检失败 {len(bad)} 处")

