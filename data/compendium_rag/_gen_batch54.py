def main() -> int:
    dump_keys = {}
    for line in DUMP.read_text(encoding="utf-8-sig").splitlines():
        line = line.strip()
        if not line:
            continue
        o = json.loads(line)
        dump_keys[o["key"]] = o["chunk_id"]

    missing = [k for k in dump_keys if k not in BATCH]
    extra = [k for k in BATCH if k not in dump_keys]
    assert not missing, f"dump 中未覆盖的块: {missing}"
    assert not extra, f"batch 中多余的 key: {extra}"

    out = ROOT / "_agent_batch54.json"
    out.write_text(json.dumps(BATCH, ensure_ascii=False, indent=1),
                   encoding="utf-8")
    print(f"写出 {len(BATCH)} 块 → {out}")
    for k in dump_keys:
        v = BATCH[k]
        print(f"  {dump_keys[k]}: {len(v['entities'])} 实体 / "
              f"{len(v['relations'])} 关系")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
