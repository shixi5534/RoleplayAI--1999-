# ================= 校验与写出 =================
def main() -> int:
    lines = [l for l in (ROOT / DUMP).read_text(encoding="utf-8").splitlines() if l.strip()]
    dump, texts = {}, {}
    for l in lines:
        o = json.loads(l)
        cid = o["chunk_id"].split(":")[-1]
        dump[cid] = o["key"]
        texts[cid] = o["text"]
    if set(dump) != set(B):
        raise SystemExit(f"[X] 块不匹配 dump={sorted(dump)} gen={sorted(B)}")

    bad = []
    for cid, blk in B.items():
        names = [e["name"] for e in blk["entities"]]
        if len(set(names)) != len(names):
            bad.append(f"{cid} 块内重名")
        for e in blk["entities"]:
            if e["type"] not in {"角色", "组织", "地点", "物品", "概念", "事件"}:
                bad.append(f"{cid} 非法 type {e['type']}")
            if e["name"] in e["aliases"]:
                bad.append(f"{cid} alias 撞本体名 {e['name']}")
        seen = set(names)
        src = re.sub(r"[“”‘’「」『』《》]", "", texts[cid])
        for r in blk["relations"]:
            if r["src"] not in seen or r["dst"] not in seen:
                bad.append(f"{cid} 端点缺失 {r['src']}->{r['dst']}")
            if not re.fullmatch(r"[一-龥]{2,6}", r["relation"]):
                bad.append(f"{cid} relation 违规 {r['relation']!r}")
            ev = re.sub(r"[“”‘’「」『』《》]", "", r["evidence"])
            if len(ev) > 40:
                bad.append(f"{cid} evidence 超长 {len(ev)} {ev[:20]}")
            if ev not in src:
                bad.append(f"{cid} evidence 不在原文: {ev[:24]}")
        # alias 必须在该块原文出现
        for e in blk["entities"]:
            for a in e["aliases"]:
                if a not in texts[cid]:
                    bad.append(f"{cid} alias {a} 未见于原文")
        blk["chunk_id"] = f"activity__35101_绿松石蛇俱乐部:{cid}"
        blk["key"] = dump[cid]

    if bad:
        for x in bad:
            print("[X]", x)
        raise SystemExit(1)

    out = {B[c]["key"]: {k: v for k, v in B[c].items() if k not in ("key", "chunk_id")} for c in B}
    (ROOT / OUT).write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    ne = sum(len(b["entities"]) for b in B.values())
    nr = sum(len(b["relations"]) for b in B.values())
    print(f"[OK] {len(B)} 块 / {ne} 实体 / {nr} 关系 → {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
