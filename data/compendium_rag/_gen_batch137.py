    forbidden = {"珍妮弗", "杰克", "汤姆"}
    for k, v in BATCH.items():
        for e in v["entities"]:
            hit = ({e["name"]} | set(e["aliases"])) & forbidden
            if hit:
                print(f"  [⚠ 冲突名] {k}: {e['name']} -> {sorted(hit)}")
    return 0


