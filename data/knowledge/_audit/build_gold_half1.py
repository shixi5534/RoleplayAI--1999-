def build():
    with open(IN_PATH, "r", encoding="utf-8-sig") as f:
        data = json.load(f)
    src_chunks = data["chunks"]
    assert [c["chunk_id"] for c in CHUNKS] == [c["chunk_id"] for c in src_chunks], "chunk order mismatch"

    counts = {"entity_agree": 0, "entity_a_only": 0, "entity_b_only": 0, "entity_dropped": 0,
              "relation_agree": 0, "relation_added_single": 0, "relation_dropped": 0}
    out_chunks = []
    for spec in CHUNKS:
        ents, rels = [], []
        for flag, body in spec["entities"]:
            counts[{"agree": "entity_agree", "a_only": "entity_a_only",
                    "b_only": "entity_b_only"}[flag]] += 1
            ents.append(body)
        for flag, body in spec["relations"]:
            counts["relation_agree" if flag == A else "relation_added_single"] += 1
            rels.append(body)
        counts["entity_dropped"] += len(spec["dropped_entities"])
        counts["relation_dropped"] += len(spec["dropped_relations"])
        out_chunks.append({"chunk_id": spec["chunk_id"], "entities": ents, "relations": rels})

    return {
        "schema": "audit.l1_gold/v1",
        "half": "1",
        "meta": {
            "n_chunks": len(out_chunks),
            "entity_agree": counts["entity_agree"],
            "entity_a_only": counts["entity_a_only"],
            "entity_b_only": counts["entity_b_only"],
            "entity_dropped": counts["entity_dropped"],
            "relation_agree": counts["relation_agree"],
            "relation_added_single": counts["relation_added_single"],
            "relation_dropped": counts["relation_dropped"],
            "notes": NOTES,
        },
        "chunks": out_chunks,
    }


