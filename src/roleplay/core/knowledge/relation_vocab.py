_SUBSTR_KEYS: tuple[str, ...] = tuple(
    sorted(
        set(CANONICAL_RELATIONS) | set(SYNONYM_MAP),
        key=lambda s: (-len(s), s),
    )
)


def _resolve_exact(rel: str) -> str | None:
    """canonical / 同义词表的精确命中。"""
    if rel in CANONICAL_SET:
        return rel
    mapped = SYNONYM_MAP.get(rel)
    if mapped:
        # 同义词表可能出现两级跳（A→B、B→C），收敛到 canonical
        return mapped if mapped in CANONICAL_SET else SYNONYM_MAP.get(mapped)
    return None


def _resolve_by_rule(rel: str) -> str | None:
    """规则归约：剥被动前缀 / 方位后缀 → 最长子串匹配。"""
    for probe in _rule_variants(rel):
        hit = _resolve_exact(probe)
        if hit:
            return hit
    # 最长子串：「计划前往」→前往、「封印记忆」→封印、「寻找线索」→寻找
    best: tuple[int, int, str] | None = None  # (-长度, 起始位置, canonical)
    for key in _SUBSTR_KEYS:
        if len(key) < 2:
            continue
        pos = rel.find(key)
        if pos < 0:
            continue
        hit = _resolve_exact(key)
        if not hit:
            continue
        cand = (-len(key), pos, hit)
        if best is None or cand < best:
            best = cand
    if best:
        return best[2]
    if len(rel) >= 3:
        return _HEAD_HINT_MAP.get(rel[0])
    return None


def _rule_variants(rel: str) -> list[str]:
    """生成剥离形态候选（保序去重）。"""
    out: list[str] = []
    seen: set[str] = set()
    stripped = _PASSIVE_PREFIX_RE.sub("", rel)
    for cand in (stripped, _TAIL_SUFFIX_RE.sub("", rel), _TAIL_SUFFIX_RE.sub("", stripped)):
        c = cand.strip()
        if len(c) >= 2 and c != rel and c not in seen:
            seen.add(c)
            out.append(c)
    return out


def classify_relation(relation: str) -> tuple[str | None, str]:
    """判定单个关系名 → ``(canonical 或 None, 原因码)``。

    判定顺序：空 → 黑名单 → 否定 → 标点 → 拉丁 → 超长 → canonical → 同义词
    → 规则归约 → 待人工审核。**否定必须早于规则归约**，否则「不隶属于」会被
    最长子串规则救成「隶属」，把否定事实写成肯定边。
    """
    rel = (relation or "").strip()
    if not rel:
        return None, REASON_DROP_EMPTY
    if rel in JUNK_BLACKLIST:
        return None, REASON_DROP_JUNK
    if _NEG_RE.match(rel):
        return None, REASON_DROP_NEGATION
    if _PUNCT_RE.search(rel):
        return None, REASON_DROP_PUNCT
    if _LATIN_RE.search(rel):
        return None, REASON_DROP_LATIN
    if len(rel) > MAX_RELATION_LEN:
        return None, REASON_DROP_LONG
    hit = _resolve_exact(rel)
    if hit:
        return hit, REASON_CANONICAL if rel in CANONICAL_SET else REASON_SYNONYM
    hit = _resolve_by_rule(rel)
    if hit:
        return hit, REASON_RULE
    return None, REASON_REVIEW


def canonicalize_relation(relation: str) -> str | None:
    """在线抽取用：映射到 canonical，映射不到（含待审核）→ None 表示丢弃。"""
    canon, _reason = classify_relation(relation)
    return canon


def is_dropped(reason: str) -> bool:
    """原因码是否属于「卫生过滤丢弃」（区别于「待人工审核」）。"""
    return reason in _DROP_REASONS


def vocab_prompt_block() -> str:
    """抽取提示词里的受控词表段（按组渲染，便于小模型对齐语义）。"""
    lines = [
        f"{name}：" + "/".join(rels) for name, rels in RELATION_GROUPS.items()
    ]
    return "；".join(lines)


